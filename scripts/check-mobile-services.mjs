import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'

await mkdir('test-results', { recursive: true })
const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ reducedMotion: 'reduce' })
const evidence = [], errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
const prices = [100, 100, 110, 165, 100, 120, 120, 110].map(price => `Starting at $${price}`)

try {
  for (const width of [320, 375, 768, 1024, 1280, 1900]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('http://localhost:5173/mobile-service', { waitUntil: 'networkidle' })
    await page.evaluate(async () => {
      [...document.images].forEach(image => { image.loading = 'eager' })
      await Promise.all([...document.images].map(image => image.decode()))
      await document.fonts.ready
    })
    await expect(page).toHaveTitle('Mobile Services | Mielle Wellness')
    await expect(page.locator('h1')).toHaveText('Mobile Services')
    await expect(page.locator('.services-page-intro p')).toHaveText('Skip the travel and enjoy professional massage therapy in the comfort of your own home. We bring care, comfort, and relaxation to you so you can fully unwind in the comfort of your own space.')
    assert.deepEqual(await page.locator('.treatment-price').allTextContents(), prices)
    await expect(page.locator('.treatment-card')).toHaveCount(8)
    await expect(page.locator('.services-submenu a[aria-current="page"]').first()).toHaveAttribute('href', '/mobile-service')
    for (const link of await page.locator('.treatment-booking, .services-booking').all()) {
      await expect(link).toHaveAttribute('href', 'https://miellewellness.noterro.com/')
      await expect(link).toHaveAttribute('target', '_blank')
    }
    const boxes = await page.locator('.treatment-card').evaluateAll(elements => elements.map(el => el.getBoundingClientRect().toJSON()))
    const columns = width >= 960 ? 3 : width >= 620 ? 2 : 1
    assert.ok(Math.abs(boxes[0].top - boxes[columns - 1].top) < 2)
    assert.ok(boxes[columns].top > boxes[0].bottom)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await expect(page.locator('#contact')).toHaveCSS('background-color', 'rgb(0, 0, 0)')
    await expect(page.locator('footer')).toHaveCSS('background-color', 'rgb(0, 0, 0)')
    if ([375, 1900].includes(width)) await page.screenshot({ path: `test-results/mobile-services-${width}.png`, fullPage: true })
    evidence.push(`${width}px: supplied Mobile Services copy and eight prices, loaded images, ${columns}-column gallery, booking destinations, dark contact/footer and no overflow`)
  }
  const nav = page.locator('.desktop-nav')
  await nav.getByRole('link', { name: 'SERVICES', exact: true }).hover()
  await nav.getByRole('link', { name: 'In-Clinic Services', exact: true }).click()
  await page.waitForURL('**/in-clinic')
  await expect(page.locator('.treatment-price').first()).toHaveText('Starting at $70')
  await nav.getByRole('link', { name: 'SERVICES', exact: true }).hover()
  await nav.getByRole('link', { name: 'Mobile Services', exact: true }).click()
  await page.waitForURL('**/mobile-service')
  await expect(page.locator('.treatment-price').first()).toHaveText('Starting at $100')
  await page.goBack()
  await expect(page.locator('h1')).toHaveText('In-Clinic Services')
  await page.goForward()
  await expect(page.locator('h1')).toHaveText('Mobile Services')
  await page.goto('http://localhost:5173/mobile-service/', { waitUntil: 'networkidle' })
  await page.reload()
  await expect(page).toHaveTitle('Mobile Services | Mielle Wellness')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.reload()
  await expect(page.locator('h1')).toHaveCSS('animation-name', 'services-enter')
  const card = page.locator('.treatment-booking').first()
  await card.hover()
  await expect.poll(() => card.locator('img').evaluate(el => new DOMMatrixReadOnly(getComputedStyle(el).transform).a)).toBeGreaterThan(1.04)
  await expect(card).toHaveCSS('text-decoration-line', 'none')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(card.locator('img')).toHaveCSS('transform', 'none')
  await nav.getByRole('link', { name: 'CONTACT', exact: true }).click()
  await page.getByRole('button', { name: 'SEND', exact: true }).click()
  assert.equal(await page.locator('#first-name').evaluate(el => el.validity.valueMissing), true)
  await page.locator('#first-name').fill('Test')
  await page.locator('#contact-email').fill('visitor@example.com')
  await page.getByRole('button', { name: 'SEND', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Open email to send', exact: true })).toHaveAttribute('href', /mailto:miellewellness@gmail.com/)
  const phone = await browser.newPage({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' })
  await phone.goto('http://localhost:5173/in-clinic', { waitUntil: 'networkidle' })
  await phone.getByRole('button', { name: 'Menu', exact: true }).tap()
  await phone.locator('.mobile-nav').getByRole('button', { name: 'Service options' }).tap()
  await phone.locator('.mobile-nav').getByRole('link', { name: 'Mobile Services', exact: true }).tap()
  await phone.waitForURL('**/mobile-service')
  await expect(phone.locator('h1')).toHaveText('Mobile Services')
  await expect(phone.locator('.mobile-nav')).toHaveCount(0)
  await phone.close()
  evidence.push('Desktop and touch dropdown navigation, distinct clinic/mobile pricing, history, refresh/trailing slash, light entrance, contained hover zoom without underlines, reduced motion and contact validation/draft pass')
  assert.deepEqual(errors, [])
  await writeFile('test-results/mobile-services-check.json', JSON.stringify({ evidence, errors }, null, 2))
  console.log(evidence.join('\n'))
} finally {
  await browser.close()
}
