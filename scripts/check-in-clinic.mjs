import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'

await mkdir('test-results', { recursive: true })
const browser = await chromium.launch({ channel: 'chrome' })
const context = await browser.newContext({ reducedMotion: 'reduce' })
const page = await context.newPage()
const errors = [], evidence = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
const visit = path => page.goto(`http://localhost:5173${path}`, { waitUntil: 'networkidle' })
const prices = [70, 70, 80, 135, 70, 90, 90, 80].map(price => `Starting at $${price}`)
const choices = ['In-Clinic Services', 'Mobile Services', 'Skin Treatment']

try {
  for (const width of [320, 375, 768, 1024, 1280, 1900]) {
    await page.setViewportSize({ width, height: 1000 })
    await visit('/in-clinic')
    await page.evaluate(async () => {
      [...document.images].forEach(image => { image.loading = 'eager' })
      await Promise.all([...document.images].map(image => image.decode()))
      await document.fonts.ready
    })
    await expect(page).toHaveTitle('In-Clinic Services | Mielle Wellness')
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('In-Clinic Services')
    await expect(page.locator('.services-page-intro p')).toHaveText('Treat yourself to a calming escape in a warm and welcoming space created for your comfort. Relax away from home, release tension, and enjoy a moment of peace just for you.')
    assert.deepEqual(await page.locator('.treatment-price').allTextContents(), prices)
    await expect(page.locator('.treatment-gallery a')).toHaveCount(8)
    for (const link of await page.locator('.treatment-gallery a, .services-booking').all()) {
      await expect(link).toHaveAttribute('href', 'https://miellewellness.noterro.com/')
      await expect(link).toHaveAttribute('target', '_blank')
    }
    await expect(page.locator('#contact')).toHaveCSS('background-color', 'rgb(0, 0, 0)')
    await expect(page.locator('footer')).toHaveCSS('background-color', 'rgb(0, 0, 0)')
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    const cards = await page.locator('.treatment-card').evaluateAll(elements => elements.map(el => el.getBoundingClientRect().toJSON()))
    const columns = width >= 960 ? 3 : width >= 620 ? 2 : 1
    assert.ok(Math.abs(cards[0].top - cards[columns - 1].top) < 2)
    assert.ok(cards[columns].top > cards[0].bottom)
    if ([375, 1900].includes(width)) await page.screenshot({ path: `test-results/in-clinic-${width}.png`, fullPage: true })
    if (width >= 1280) {
      const nav = page.locator('.desktop-nav')
      const submenu = nav.locator('.services-submenu')
      await nav.getByRole('link', { name: 'SERVICES', exact: true }).hover()
      await expect(submenu).toBeVisible()
      assert.deepEqual(await submenu.locator('a').allTextContents(), choices)
      await submenu.getByRole('link', { name: 'In-Clinic Services', exact: true }).hover()
      await expect(submenu).toBeVisible()
      await expect(submenu.getByRole('link', { name: 'In-Clinic Services', exact: true })).toHaveAttribute('aria-current', 'page')
      const bounds = await submenu.boundingBox()
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width)
      await page.screenshot({ path: `test-results/services-dropdown-${width}.png` })
      await page.keyboard.press('Escape')
      await expect(submenu).toBeHidden()
      await page.mouse.move(width - 10, 300)
      await nav.getByRole('link', { name: 'SERVICES', exact: true }).hover()
      await expect(submenu).toBeVisible()
      await page.mouse.move(width - 10, 300)
      await expect(submenu).toBeHidden()
    }
    evidence.push(`${width}px: exact In-Clinic copy/prices, eight loaded treatment images and booking links, ${columns}-column layout, dark contact/footer, no overflow${width >= 1280 ? ', three hover choices remain reachable inside the viewport' : ''}`)
  }

  const nav = page.locator('.desktop-nav')
  const trigger = nav.getByRole('button', { name: 'Service options' })
  const submenu = nav.locator('.services-submenu')
  await nav.getByRole('link', { name: 'SERVICES', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(submenu.getByRole('link', { name: 'In-Clinic Services', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(submenu).toBeHidden()
  await expect(trigger).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Tab')
  await expect(submenu.getByRole('link', { name: 'In-Clinic Services', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(submenu.getByRole('link', { name: 'Skin Treatment', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(submenu).toBeHidden()
  await trigger.focus()
  await page.keyboard.press('Enter')
  await page.locator('h1').click()
  await expect(submenu).toBeHidden()
  await nav.getByRole('link', { name: 'SERVICES', exact: true }).hover()
  await expect(submenu.getByRole('link', { name: 'Mobile Services' })).toHaveAttribute('href', '/mobile-service')
  await expect(submenu.getByRole('link', { name: 'Skin Treatment' })).toHaveAttribute('href', 'https://www.miellewellness.ca/skin-treatment')
  await submenu.getByRole('link', { name: 'In-Clinic Services', exact: true }).click()
  await expect(page).toHaveURL('http://localhost:5173/in-clinic')
  await visit('/in-clinic/')
  await page.reload()
  await expect(page).toHaveTitle('In-Clinic Services | Mielle Wellness')
  await nav.getByRole('link', { name: 'SERVICES', exact: true }).click()
  await page.waitForURL('**/services')
  await expect(page.locator('.treatment-price')).toHaveCount(0)
  await page.goBack()
  await expect(page).toHaveTitle('In-Clinic Services | Mielle Wellness')
  await context.route('https://miellewellness.noterro.com/**', route => route.fulfill({ contentType: 'text/html', body: '<title>Booking destination</title>' }))
  const popupPromise = page.waitForEvent('popup')
  await page.getByRole('link', { name: 'BOOK NOW', exact: true }).click()
  const popup = await popupPromise
  await popup.waitForLoadState()
  assert.equal(popup.url(), 'https://miellewellness.noterro.com/')
  await popup.close()
  evidence.push('Desktop hover, pointer travel, keyboard ArrowDown/Enter/Tab/Escape, focus restoration, outside click, all destinations, direct route/trailing slash/reload/history and in-clinic booking pass')

  const mobile = await browser.newPage({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' })
  await mobile.goto('http://localhost:5173/', { waitUntil: 'networkidle' })
  await mobile.getByRole('button', { name: 'Menu', exact: true }).tap()
  const mobileNav = mobile.locator('.mobile-nav')
  const mobileTrigger = mobileNav.getByRole('button', { name: 'Service options' })
  await mobileTrigger.tap()
  await expect(mobileNav.locator('.services-submenu')).toBeVisible()
  await mobile.screenshot({ path: 'test-results/services-dropdown-mobile.png' })
  await mobile.keyboard.press('Escape')
  await expect(mobileNav).toBeVisible()
  await expect(mobileNav.locator('.services-submenu')).toBeHidden()
  await expect(mobileTrigger).toBeFocused()
  await mobileTrigger.tap()
  await mobileNav.getByRole('link', { name: 'In-Clinic Services', exact: true }).tap()
  await mobile.waitForURL('**/in-clinic')
  await expect(mobileNav).toHaveCount(0)
  await expect(mobile.locator('h1')).toHaveText('In-Clinic Services')
  await mobile.close()
  evidence.push('Touch menu expands the three options; Escape closes the submenu first; selecting In-Clinic opens the new page and closes navigation')
  assert.deepEqual(errors, [])
  await writeFile('test-results/in-clinic-check.json', JSON.stringify({ evidence, errors }, null, 2))
  console.log(evidence.join('\n'))
} finally {
  await browser.close()
}
